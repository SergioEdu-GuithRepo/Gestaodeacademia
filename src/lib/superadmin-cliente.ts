/** Normaliza um texto para slug de centro (ex.: "Centro Formar+" → "centro-formar"). */
export function gerarSlugCentro(texto: string): string {
  return texto
    .normalize("NFD")
    .replace(/[\u0300-\u036f]/g, "")
    .toLowerCase()
    .replace(/[^a-z0-9]+/g, "-")
    .replace(/^-+|-+$/g, "")
    .slice(0, 50);
}
